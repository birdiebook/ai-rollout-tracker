from ai_tracker.catalog import Spec
from ai_tracker.sources import indeed

LICENSE = ("CC BY 4.0 (github.com/hiring-lab/ai-tracker README/LICENSE): \"The data generated by Indeed "
           "Hiring Lab are available under the Creative Commons Attribution 4.0 International License ... "
           "freely available for public use, as long as Hiring Lab is cited as a source.\"")

COUNTRIES = {"US": "USA", "GB": "Storbritannien", "DE": "Tyskland", "FR": "Frankrike", "CA": "Kanada",
             "AU": "Australien", "IE": "Irland", "IT": "Italien", "NL": "Nederländerna"}

SPECS = [
    Spec(
        key=f"ai_postings_share_{cc.lower()}_d",
        branch="G8",
        label=f"Andel platsannonser som nämner AI, {name} (Indeed)",
        unit="% av annonserna, 7-dagars glidande medel",
        freq="D",
        source="Indeed Hiring Lab, github.com/hiring-lab/ai-tracker (AI_posting.csv)",
        fetch=partial(indeed.fetch, cc),
        lag_days=17,  # ignored (release-dated); last day of a vintage is typically 2-3 weeks old
        license=LICENSE,
        revised=True,
        publish=True,
        question="Hur snabbt sprids AI-kompetens som krav i arbetsmarknaden?",
        note="Hela historiken räknas om vid varje uppdatering (ungefär månadsvis). Metoden ändrades "
             "2024-07 (glidande medel) och 2024-09 (harmonisering), vilket syns som revideringar.",
    )
    for cc, name in COUNTRIES.items()
]
